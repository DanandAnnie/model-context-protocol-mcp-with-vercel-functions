"use client";
import { useEffect, useRef, useState } from "react";
import { Download, ImagePlus, MonitorPlay, Trash2, X } from "lucide-react";
import { Button, Card, EmptyState, ErrorBanner, SectionTitle, StatusBadge, inputClass } from "@/components/ui";
import { useApi } from "@/hooks/useApi";
import { useCanEdit } from "@/hooks/useCanEdit";
import { useFocusAfterRender } from "@/hooks/useFocusAfterRender";
import { ViewOnlyNotice } from "@/components/ViewOnlyNotice";
import { api, formatDate, isRefusal } from "@/lib/client";
import { toUploadable } from "@/lib/image-upload";
import { FOOTAGE_ASPECTS, FOOTAGE_MAX_SEC, FOOTAGE_MIN_SEC, footagePath, type FootageAspect, type FootageJob } from "@/lib/types";

/** A clip as the server lists it: never the renderer, its job id, or the picture's digest. */
type Footage = Omit<FootageJob, "ownerId" | "provider" | "providerJobId" | "imageDigest">;
/** A fresh key for one start (a UUID where the browser has one, as it does over https and on localhost). */
const newKey = () => (typeof crypto !== "undefined" && "randomUUID" in crypto ? crypto.randomUUID() : `k${Date.now().toString(36)}${Math.random().toString(36).slice(2, 12)}`);
/** Clips' links are renewed by the server once this old; a page left open asks again when it is looked at. */
const RELINK_MS = 30 * 60 * 1000;
const MAX_PROMPT = 2000;
const MAX_PICTURE_BYTES = 3 * 1024 * 1024;
const FRAMES: Record<FootageAspect, string> = { "16:9": "Landscape 16:9", "9:16": "Portrait 9:16", "1:1": "Square 1:1" };

/**
 * "B-roll": short clips generated by the renderer from a description of the shot, or brought to life from a picture as
 * their first frame (HeyGen Video). Each is listed to watch and download, and can loop behind a presenter as a scene's
 * video background (chosen in the editor's Background tab).
 */
export default function FootagePage() {
  const canEdit = useCanEdit();
  const { data, error, setData, refetch } = useApi<{ footage: Footage[]; available: boolean }>("/api/footage");
  // While a clip is being made the list is asked again, only while the tab is visible.
  const running = (data?.footage ?? []).some((f) => f.status === "processing");
  useEffect(() => {
    if (!running) return;
    const timer = setInterval(() => {
      if (document.visibilityState === "visible") void refetch();
    }, 10_000);
    return () => clearInterval(timer);
  }, [running, refetch]);
  const [prompt, setPrompt] = useState("");
  const [durationSec, setDurationSec] = useState(FOOTAGE_MIN_SEC);
  const [aspect, setAspect] = useState<FootageAspect>("16:9");
  const [quality, setQuality] = useState<"standard" | "hd">("standard");
  const [picture, setPicture] = useState<{ name: string; url: string } | null>(null);
  const [reading, setReading] = useState(false);
  const [title, setTitle] = useState("");
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  const [note, setNote] = useState<string | null>(null);
  // One key per start: a retry of the same start (after a timeout, say) sends it again and gets the same clip back.
  const [requestKey, setRequestKey] = useState(() => newKey());
  const promptRef = useRef<HTMLTextAreaElement>(null);
  const fileRef = useRef<HTMLInputElement>(null);
  const listRef = useRef<HTMLDivElement>(null);
  const headingRef = useRef<HTMLHeadingElement>(null);
  const focusAfterRender = useFocusAfterRender();
  const changed = () => {
    setErr(null);
    setRequestKey(newKey());
  };
  // A clip that is made or fails while the page is open is announced.
  const seen = useRef<Map<string, Footage["status"]>>(new Map());
  useEffect(() => {
    if (!data) return;
    const parts: string[] = [];
    for (const f of data.footage) {
      const before = seen.current.get(f.id);
      if (before === "processing" && f.status !== "processing") parts.push(f.status === "completed" ? `${f.title} is ready.` : `${f.title} could not be made: ${f.error ?? "the renderer failed"}.`);
      seen.current.set(f.id, f.status);
    }
    if (parts.length) setNote(parts.join(" "));
  }, [data]);
  // A page left open past the links' lifetime asks again when it is looked at, so the players and links still work.
  const loadedAt = useRef(Date.now());
  useEffect(() => {
    const onVisible = () => {
      if (document.visibilityState === "visible" && Date.now() - loadedAt.current > RELINK_MS) {
        loadedAt.current = Date.now();
        void refetch();
      }
    };
    document.addEventListener("visibilitychange", onVisible);
    return () => document.removeEventListener("visibilitychange", onVisible);
  }, [refetch]);

  const items = data?.footage ?? [];
  const canStart = canEdit !== false && data?.available !== false;
  const shortPrompt = prompt.trim().length < 10;
  // HeyGen makes HD clips in landscape or portrait only; a clip from a picture takes the picture's shape.
  const hdBlocked = !picture && aspect === "1:1";

  async function choosePicture(input: HTMLInputElement) {
    const file = input.files?.[0];
    input.value = "";
    if (!file) return;
    // The control stays enabled while busy (disabling it would drop its focus); a pick made then is not taken, and the
    // page says so.
    if (busy || reading) {
      setErr(reading ? "Still reading the picture added before; add this one again in a moment." : "Wait for the clip to be started, then add the picture again.");
      return;
    }
    setReading(true);
    changed();
    try {
      setPicture({ name: file.name, url: await toUploadable(file, { maxBytes: MAX_PICTURE_BYTES, maxEdge: 2048 }) });
    } catch (e) {
      setErr(e instanceof Error ? e.message : "That picture could not be read");
    } finally {
      setReading(false);
    }
  }

  function removePicture() {
    setPicture(null);
    changed();
    // The focus goes to the control that adds one, which takes the remove button's place.
    focusAfterRender(() => fileRef.current);
  }

  async function submit() {
    setBusy(true);
    setErr(null);
    setNote(null);
    try {
      const body = {
        prompt: prompt.trim(),
        durationSec,
        ...(picture ? { image: picture.url } : { aspect }),
        quality: hdBlocked ? "standard" : quality,
        ...(title.trim() ? { title: title.trim() } : {}),
      };
      const { footage } = await api<{ footage: Footage }>("/api/footage", { method: "POST", body: JSON.stringify(body), headers: { "Idempotency-Key": requestKey } });
      setData((prev) => ({ available: prev?.available ?? true, footage: [footage, ...(prev?.footage ?? []).filter((f) => f.id !== footage.id)] }));
      // A check that left before this clip was started would answer without it; asking again retires it.
      void refetch();
      setRequestKey(newKey());
      setPrompt("");
      setPicture(null);
      setTitle("");
      setNote(`Making ${footage.title}; it appears here when it is ready.`);
      // Focus goes to the new clip, rather than being lost with the cleared form.
      focusAfterRender(() => listRef.current?.querySelector<HTMLElement>(`[data-footage="${footage.id}"]`) ?? promptRef.current);
    } catch (e) {
      setErr(e instanceof Error ? e.message : "The clip could not be started");
      // A refusal is an answer: trying again is a new start. A lost answer keeps its key, so a retry returns the same clip.
      if (isRefusal(e)) setRequestKey(newKey());
    } finally {
      setBusy(false);
    }
  }

  async function remove(f: Footage) {
    if (!window.confirm(`Delete “${f.title}”? Scenes that loop it can no longer be rendered, and making it again uses another job.`)) return;
    setErr(null);
    setNote(null);
    const next = items[items.indexOf(f) + 1] ?? items[items.indexOf(f) - 1];
    try {
      seen.current.delete(f.id);
      await api(`/api/footage/${f.id}`, { method: "DELETE" });
      setData((prev) => (prev ? { ...prev, footage: prev.footage.filter((x) => x.id !== f.id) } : prev));
      void refetch();
      setNote(`Deleted ${f.title}.`);
      // Focus moves to the next clip, or to the list's heading, rather than being lost with the button.
      focusAfterRender(() => (next ? listRef.current?.querySelector<HTMLElement>(`[data-footage="${next.id}"]`) : headingRef.current));
    } catch (e) {
      setErr(e instanceof Error ? e.message : "The clip could not be deleted");
    }
  }

  return (
    <>
      <SectionTitle title="B-roll" subtitle="Describe a shot, or bring a picture to life, and get a short clip to download or loop behind a presenter." />
      {canEdit === false && <ViewOnlyNotice what="make clips" />}
      <ErrorBanner message={error} />
      <p role="status" className="sr-only">
        {note ?? ""}
      </p>
      <div className="grid grid-cols-1 gap-6 lg:grid-cols-[1fr_1.4fr]">
        <Card className="p-5">
          {data?.available === false ? (
            <p className="text-sm text-slate-600">Generated clips need the HeyGen renderer; the current renderer has no such feature.</p>
          ) : (
            <div className="space-y-4">
              <div>
                <label htmlFor="footage-prompt" className="mb-1.5 block text-sm font-medium text-slate-700">
                  Describe the shot
                </label>
                <textarea
                  id="footage-prompt"
                  ref={promptRef}
                  className={`${inputClass} min-h-28`}
                  value={prompt}
                  maxLength={MAX_PROMPT}
                  disabled={canEdit === false}
                  aria-describedby="footage-prompt-hint"
                  placeholder="A slow push-in on a sunlit kitchen; steam rises from a coffee cup on the counter"
                  onChange={(e) => (setPrompt(e.target.value), changed())}
                />
                <p id="footage-prompt-hint" className="mt-1 text-xs text-slate-500">
                  What is seen, what happens, and how the camera moves. {prompt.length} of {MAX_PROMPT} characters.
                </p>
              </div>
              <div>
                <div className="mb-1.5 text-sm font-medium text-slate-700" id="footage-picture-label">
                  Start from a picture (optional)
                </div>
                <p className="mb-2 text-xs text-slate-500" id="footage-picture-hint">
                  The clip opens on the picture exactly as it looks and takes its shape. PNG or JPEG; other pictures are converted.
                </p>
                {picture ? (
                  <div className="flex items-center gap-3">
                    {/* eslint-disable-next-line @next/next/no-img-element */}
                    <img src={picture.url} alt={picture.name} className="h-16 w-24 rounded-md bg-slate-100 object-cover" />
                    <button type="button" onClick={removePicture} disabled={busy} className="inline-flex items-center gap-1 rounded-lg border border-slate-200 px-2 py-1 text-xs text-slate-600 hover:bg-slate-50" aria-label={`Remove ${picture.name}`}>
                      <X className="h-3.5 w-3.5" aria-hidden /> Remove
                    </button>
                  </div>
                ) : (
                  <label className={`inline-flex cursor-pointer items-center gap-2 rounded-lg border border-slate-200 bg-white px-3 py-1.5 text-sm text-slate-700 hover:bg-slate-50 focus-within:ring-2 focus-within:ring-brand-500 ${busy || reading || canEdit === false ? "opacity-60" : ""}`}>
                    <input ref={fileRef} type="file" accept="image/*" className="sr-only" aria-describedby="footage-picture-hint" aria-disabled={busy || reading || canEdit === false} disabled={canEdit === false} onChange={(e) => choosePicture(e.currentTarget)} />
                    <ImagePlus className="h-4 w-4" aria-hidden /> {reading ? "Reading…" : "Add a picture"}
                  </label>
                )}
              </div>
              <div>
                <label htmlFor="footage-length" className="mb-1.5 block text-sm font-medium text-slate-700">
                  Length: {durationSec} seconds
                </label>
                <input id="footage-length" type="range" min={FOOTAGE_MIN_SEC} max={FOOTAGE_MAX_SEC} step={1} value={durationSec} disabled={canEdit === false} onChange={(e) => (setDurationSec(Number(e.target.value)), changed())} className="w-full accent-brand-600" />
              </div>
              <fieldset disabled={!!picture || canEdit === false}>
                <legend className="mb-1.5 text-sm font-medium text-slate-700">Frame</legend>
                {picture ? (
                  <p className="text-xs text-slate-500">The picture&apos;s own shape.</p>
                ) : (
                  <div className="flex flex-wrap gap-4 text-sm text-slate-700">
                    {FOOTAGE_ASPECTS.map((a) => (
                      <label key={a} className="flex items-center gap-2">
                        <input type="radio" name="footage-frame" className="accent-brand-600" checked={aspect === a} onChange={() => {
                            setAspect(a);
                            // A square clip cannot be HD: the choice is moved to standard, and stays there when the frame changes back.
                            if (a === "1:1") setQuality("standard");
                            changed();
                          }} />
                        {FRAMES[a]}
                      </label>
                    ))}
                  </div>
                )}
              </fieldset>
              <fieldset disabled={canEdit === false}>
                <legend className="mb-1.5 text-sm font-medium text-slate-700">Quality</legend>
                <div className="flex flex-wrap gap-4 text-sm text-slate-700">
                  <label className="flex items-center gap-2">
                    <input type="radio" name="footage-quality" className="accent-brand-600" checked={quality === "standard" || hdBlocked} onChange={() => (setQuality("standard"), changed())} onClick={() => setQuality("standard")} />
                    Standard (768p)
                  </label>
                  <label className="flex items-center gap-2">
                    <input type="radio" name="footage-quality" className="accent-brand-600" checked={quality === "hd" && !hdBlocked} disabled={hdBlocked} aria-describedby="footage-hd-hint" onChange={() => (setQuality("hd"), changed())} />
                    HD (1080p)
                  </label>
                </div>
                <p id="footage-hd-hint" className="mt-1 text-xs text-slate-500">
                  {hdBlocked ? "HD clips are landscape or portrait, not square." : "HD costs three times as much as standard."}
                </p>
              </fieldset>
              <div>
                <label htmlFor="footage-title" className="mb-1.5 block text-sm font-medium text-slate-700">
                  Title (optional)
                </label>
                <input id="footage-title" className={inputClass} value={title} maxLength={120} disabled={canEdit === false} onChange={(e) => (setTitle(e.target.value), changed())} placeholder="The start of the description" />
              </div>
              {/* A refusal is shown by the button that was pressed, so it is seen on a phone too. */}
              <ErrorBanner message={err} />
              <Button onClick={submit} loading={busy} disabled={shortPrompt || reading || !canStart} className="w-full" aria-describedby={shortPrompt ? "footage-start-note" : undefined}>
                <MonitorPlay className="h-4 w-4" /> Make the clip
              </Button>
              {shortPrompt && (
                <p id="footage-start-note" className="text-xs text-slate-500">
                  Describe the shot in a few words first.
                </p>
              )}
            </div>
          )}
        </Card>

        <div ref={listRef}>
          <h2 ref={headingRef} tabIndex={-1} className="mb-3 text-sm font-semibold text-slate-900 outline-none">
            Your clips
          </h2>
          {!data ? null : items.length === 0 ? (
            <EmptyState icon={<MonitorPlay className="h-8 w-8" />} title="No clips yet" body="Describe a shot on the left to make one." />
          ) : (
            <div className="space-y-3">
              {items.map((f) => (
                <Card key={f.id} className="p-4 outline-none focus:ring-2 focus:ring-brand-500" data-testid="footage" data-footage={f.id} tabIndex={-1}>
                  <div className="flex items-start justify-between gap-3">
                    <div className="min-w-0">
                      <div className="truncate text-sm font-medium text-slate-900">{f.title}</div>
                      <div className="mt-0.5 text-xs text-slate-500" data-testid="footage-meta">
                        {f.durationSec} s · {f.fromPicture ? "from a picture" : f.aspect} · {f.quality === "hd" ? "HD" : "standard"} · {formatDate(f.createdAt)}
                      </div>
                      <div className="mt-1 line-clamp-2 break-words text-xs text-slate-600" title={f.prompt}>
                        {f.prompt}
                      </div>
                      {f.error && <div className="mt-1 text-xs text-rose-600">{f.error}</div>}
                    </div>
                    <div className="flex shrink-0 items-center gap-2">
                      <StatusBadge status={f.status} />
                      {canEdit !== false && (
                        <button type="button" onClick={() => remove(f)} className="rounded p-1 text-slate-400 hover:bg-slate-100 hover:text-rose-600" aria-label={`Delete ${f.title}`}>
                          <Trash2 className="h-4 w-4" />
                        </button>
                      )}
                    </div>
                  </div>
                  {f.status === "completed" && f.videoUrl && (
                    <>
                      <video src={f.videoUrl} controls preload="none" className="mt-3 w-full rounded-lg bg-black" aria-label={f.title} />
                      <div className="mt-2 flex flex-wrap items-center gap-3 text-xs">
                        <a href={f.videoUrl} download target="_blank" rel="noopener noreferrer" className="inline-flex items-center gap-1 font-medium text-brand-700 hover:underline" aria-label={`Download ${f.title}`}>
                          <Download className="h-3 w-3" aria-hidden /> Download
                        </a>
                        <span className="text-slate-500" data-testid="footage-use" data-path={footagePath(f.id)}>
                          Loop it behind a presenter: choose it under Generated clip in the editor&apos;s Background tab.
                        </span>
                      </div>
                    </>
                  )}
                </Card>
              ))}
            </div>
          )}
        </div>
      </div>
    </>
  );
}
